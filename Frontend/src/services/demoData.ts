function crimesPorArtigo(ids: number[]) {
  return ids.map((id) => {
    const a = DEMO_CODIGO_PENAL.find((x) => x.id === id)!
    return {
      artigoId: a.id,
      artigo: a.artigo,
      crime: a.crime,
      tempoMeses: a.tempoMeses,
      valorMulta: a.valorMulta,
      valorFianca: a.valorFianca,
      tornozeleira: a.tornozeleira,
      permiteFianca: a.permiteFianca,
    }
  })
}

function soma(ids: number[], campo: 'tempoMeses' | 'valorMulta') {
  return crimesPorArtigo(ids).reduce((s, c) => s + c[campo], 0)
}

